#!/bin/bash
# Generate Tom/Layout.lean: the C layout and constants of libtommath as the
# cross compiler sees them (offsets, sizes, MP_DIGIT_BIT, MP_MASK, the
# mp_ord/mp_sign/mp_err codes).   scripts/gen_layout.sh [DIGIT]
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
DIGIT=${1:-MP_32BIT}
TC=$(ls -d "$HOME"/toolchains/xpack-riscv-none-elf-gcc-15.2.0-*/bin | head -1)
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT
cat > "$work/probe.c" <<'C'
#include <stddef.h>
#include "tommath.h"
#define K(name, v) __asm__ volatile (".ascii \"@@" #name " %0@@\"" :: "i"((long)(v)));
void probe(void) {
  K(offUsed, offsetof(mp_int, used)) K(offAlloc, offsetof(mp_int, alloc))
  K(offSign, offsetof(mp_int, sign)) K(offDp, offsetof(mp_int, dp))
  K(sizeofMpInt, sizeof(mp_int)) K(sizeofDigit, sizeof(mp_digit))
  K(sizeofSign, sizeof(mp_sign)) K(sizeofUsed, sizeof(((mp_int*)0)->used))
  K(digitBits, MP_DIGIT_BIT) K(mpMask, MP_MASK)
  K(mpZpos, MP_ZPOS) K(mpNeg, MP_NEG)
  K(mpLt, MP_LT) K(mpEq, MP_EQ) K(mpGt, MP_GT)
  K(mpOkay, MP_OKAY) K(mpErr, MP_ERR) K(mpMem, MP_MEM) K(mpVal, MP_VAL)
}
C
"$TC/riscv-none-elf-gcc" -std=gnu11 -O2 -march=rv64i -mabi=lp64 -mcmodel=medany -D"$DIGIT" \
  -I"$root/vendor/libtommath" -S -o "$work/probe.s" "$work/probe.c"
{
  echo "/-! Generated by scripts/gen_layout.sh ($DIGIT, xPack GCC 15.2.0, rv64i/lp64): the"
  echo "libtommath layout and constants as the cross compiler sees them. Do not edit. -/"
  echo
  echo "namespace Tom.Layout"
  echo
  grep -o '@@[A-Za-z]* -\?[0-9]*@@' "$work/probe.s" | sed 's/@@//g' |
    while read -r name v; do
      case $name in
        mpLt|mpEq|mpGt|mpOkay|mpErr|mpMem|mpVal) echo "def $name : Int := $v" ;;
        *) echo "def $name : Nat := $v" ;;
      esac
    done
  echo
  echo "end Tom.Layout"
} > "$root/Tom/Layout.lean"
