#!/usr/bin/env python3
"""Generate Tom/Machine/Seg/<Fn>.lean from experiments/segs/<fn>.json: one
`#derive_case` chain per entry, emitted by scripts/emit_derive_case.py
over experiments/disasm.txt (the proof image's disassembly).

    scripts/gen_segs.py clamp Clamp
Each JSON entry is a list of blocks [start, end_exclusive_body, term], term
null | ["br", taken] | "j" | "jr" (the terminator sits at end_exclusive_body)."""
import json, os, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
src, mod = sys.argv[1], sys.argv[2]
subprocess.run(['bash', '-c', 'objdump=$(ls -d ~/toolchains/xpack-riscv-none-elf-gcc-15.2.0-*/bin | head -1)/riscv-none-elf-objdump; '
                '$objdump -d c/tommath-arith.elf > experiments/disasm.txt'], check=True)
spec = f'experiments/segs/{src}.json'
# Cut each block after a store that is not its last body instruction, so the
# instructions after a store are fetched from a `writeLog` memory (block
# boundary) rather than a nest of `stepMemM`s inside one block: the code-frame
# "Obstructions".
import re, tempfile
STORES = ('sb', 'sh', 'sw', 'sd')
ins = {}
for l in open('experiments/disasm.txt'):
    m = re.match(r'^\s+([0-9a-f]+):\t([0-9a-f]{8})\s+\t(\S+)', l)
    if m: ins[int(m.group(1), 16)] = m.group(3)
def split(blocks):
    out = []
    for s0, e0, t in blocks:
        s0, e0 = int(s0, 16), int(e0, 16)
        cur = s0
        for a in range(s0, e0, 4):
            if ins.get(a) in STORES and a + 4 < e0:
                out.append([hex(cur), hex(a + 4), None]); cur = a + 4
        out.append([hex(cur), hex(e0), t])
    return out
chains = {k: split(v) for k, v in json.load(open(spec)).items()}
with tempfile.NamedTemporaryFile('w', suffix='.json', delete=False) as f:
    json.dump(chains, f)
body = subprocess.run([sys.executable, 'scripts/emit_derive_case.py', f.name],
                      capture_output=True, text=True, check=True).stdout
os.unlink(f.name)
out = f"""import Tom.Machine.Kit.At

/-! Generated by scripts/gen_segs.py from {spec} (c/tommath-arith.elf). Do not edit:
change the JSON and regenerate. -/

namespace Tom.Machine.Seg

open LeanRV64DExecutable Vsa Vsa.Sim

{body}
end Tom.Machine.Seg
"""
open(f'Tom/Machine/Seg/{mod}.lean', 'w').write(out)
print(f'gen_segs: {len(json.load(open(spec)))} chains -> Tom/Machine/Seg/{mod}.lean')
