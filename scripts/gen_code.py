#!/usr/bin/env python3
"""Generate Tom/Machine/Code.lean: the instruction words of every libtommath
function of the proof image c/tommath-arith.elf and of everything they call
(newlib, libgcc), read with the cross objdump, plus the image's SHA-256 (so a
rebuilt image is noticed); and Tom/Machine/Img.lean: `Img m`, all of that code
in memory as one predicate (one field per function), with its read footprint
`Img.reads` (the text section `textIv`).

    scripts/gen_code.py            # regenerate
Never hand-edit the outputs."""
import hashlib, os, re, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ELF = os.path.join(ROOT, 'c/tommath-arith.elf')
OUT = os.path.join(ROOT, 'Tom/Machine/Code.lean')
OUT_IMG = os.path.join(ROOT, 'Tom/Machine/Img.lean')
TC = [d for d in os.listdir(os.path.expanduser('~/toolchains')) if d.startswith('xpack-riscv-none-elf-gcc-15.2.0')]
OBJDUMP = os.path.expanduser(f'~/toolchains/{sorted(TC)[0]}/bin/riscv-none-elf-objdump')

def lean_name(f):
    parts = f.strip('_').split('_')
    return parts[0] + ''.join(p.capitalize() for p in parts[1:])

dis = subprocess.run([OBJDUMP, '-d', ELF], capture_output=True, text=True, check=True).stdout
funcs, calls, cur = {}, {}, None
for line in dis.splitlines():
    m = re.match(r'^([0-9a-f]+) <([^>]+)>:$', line)
    if m:
        cur = m.group(2); funcs[cur] = (int(m.group(1), 16), []); calls[cur] = set(); continue
    m = re.match(r'^\s+([0-9a-f]+):\t([0-9a-f]{8})\s', line)
    if m and cur is not None:
        funcs[cur][1].append((int(m.group(1), 16), int(m.group(2), 16)))
        # calls, tail jumps, and branches into another function (`__divdi3`'s
        # sign fix-ups run inside `__umoddi3`)
        c = re.search(r'\s(?:jal|j|beq|bne|blt|bge|bltu|bgeu|beqz|bnez|bltz|bgez|blez|bgtz)\s+'
                      r'(?:[a-z0-9]+,)*[0-9a-f]+ <([^+>]+)(?:\+0x[0-9a-f]+)?>', line)
        if c and c.group(1) != cur:
            calls[cur].add(c.group(1))
    elif re.match(r'^\s+[0-9a-f]+:\t[0-9a-f]{4}\s', line):
        sys.exit(f'gen_code: compressed instruction in {cur}')
# every libtommath function, and the closure of what they call, in address order
todo = [f for f in funcs if f.startswith(('mp_', 's_mp_'))] + ['malloc']  # the allocator proofs run through `malloc`
seen = set()
while todo:
    f = todo.pop()
    if f not in seen:
        seen.add(f); todo += sorted(calls[f])
FUNCS = sorted(seen, key=lambda f: funcs[f][0])
sha = hashlib.sha256(open(ELF, 'rb').read()).hexdigest()
out = ['/-! Generated by scripts/gen_code.py from c/tommath-arith.elf', f'(SHA-256 {sha}).',
       'The instruction words of the functions the machine proofs cover. Do not edit. -/', '',
       'namespace Tom.Machine.Code', '']
for f in FUNCS:
    base, ins = funcs[f]
    for (a, _), (b, _) in zip(ins, ins[1:]):
        assert b == a + 4, f
    n = lean_name(f)
    out.append(f'/-- `{f}`: {len(ins)} instructions at [0x{base:x}, 0x{base + 4 * len(ins):x}). -/')
    out.append(f'def {n}Base : Nat := 0x{base:x}')
    ws = [f'0x{w:08x}#32' for _, w in ins]
    rows = [', '.join(ws[i:i + 6]) for i in range(0, len(ws), 6)]
    out.append(f'def {n}Code : List (BitVec 32) :=\n  [' + ',\n   '.join(rows) + ']')
    out.append('')
text = re.search(r'\.text\s+PROGBITS\s+([0-9a-f]+)\s+[0-9a-f]+\s+([0-9a-f]+)',
                 subprocess.run([OBJDUMP.replace('objdump', 'readelf'), '-SW', ELF], capture_output=True,
                                text=True, check=True).stdout)
tlo, tlen = int(text.group(1), 16), int(text.group(2), 16)
secs = subprocess.run([OBJDUMP.replace('objdump', 'readelf'), '-SW', ELF], capture_output=True, text=True,
                      check=True).stdout
ro = re.search(r'\.rodata\s+PROGBITS\s+([0-9a-f]+)\s+([0-9a-f]+)\s+([0-9a-f]+)', secs)
rlo, roff, rlen = int(ro.group(1), 16), int(ro.group(2), 16), int(ro.group(3), 16)
rbytes = open(ELF, 'rb').read()[roff:roff + rlen]
assert tlo + tlen <= rlo
# the read-only image: the text section through the end of .rodata
tlen = rlo + rlen - tlo
for f in FUNCS:
    base, ins = funcs[f]
    assert tlo <= base and base + 4 * len(ins) <= tlo + tlen, f
out.append('/-- `.rodata`: its address and bytes. -/')
out.append(f'def rodataBase : Nat := 0x{rlo:x}')
rb = [f'0x{b:02x}#8' for b in rbytes]
out.append('def rodataBytes : List (BitVec 8) :=\n  [' + ',\n   '.join(', '.join(rb[i:i + 16]) for i in range(0, len(rb), 16)) + ']')
out.append('')
out.append('/-- The read-only image: `.text` through the end of `.rodata`. -/')
out.append(f'def textBase : Nat := 0x{tlo:x}')
out.append(f'def textLen : Nat := 0x{tlen:x}')
out.append('')
out.append('end Tom.Machine.Code')
open(OUT, 'w').write('\n'.join(out) + '\n')

img = ['import Tom.Machine.Code', 'import Tom.Machine.Kit.Frame', '',
       '/-! Generated by scripts/gen_code.py from c/tommath-arith.elf. Do not edit.',
       '',
       '`Img m`: the code of every function of `Tom/Machine/Code.lean` is in `m`',
       '(one `CodeAt` field per function). It reads only the text section',
       '`textIv` (`Img.reads`), so one read-only region carries all code. It also',
       'holds `.rodata` (`RoAt`: the tables `mp_cnt_lsb` and the radix routines read). -/', '',
       'namespace Tom.Machine', '', 'open Tom.Machine.Code', '',
       '/-- The read-only image (text and rodata). -/', 'def textIv : Iv := ⟨textBase, textLen⟩', '',
       '/-- The `.rodata` bytes are in `m`. -/',
       'def RoAt (m : Mem) : Prop := ∀ i b, rodataBytes[i]? = some b → m[rodataBase + i]? = some b', '',
       '/-- All the code, and the rodata. -/', 'structure Img (m : Mem) : Prop where',
       '  rodata : RoAt m']
for f in FUNCS:
    n = lean_name(f)
    img.append(f'  {n} : CodeAt m {n}Base {n}Code')
img += ['', '/-- `Img` reads only the text section. -/',
        'theorem Img.reads {ι : Type} {ρ : ι → Iv} {r : ι} (h : textIv.Sub (ρ r)) :',
        '    Reads ρ [r] Img := fun M M\' hs hv =>',
        '  have hs\' : ∀ x, textBase ≤ x → x < textBase + textLen → M\'[x]? = M[x]? := fun x h1 h2 =>',
        '    hs x (Or.inl (by unfold Iv.Sub Iv.In textIv at *; simp only at *; omega))',
        '  have hk : ∀ {b k : Nat} {ws : List (BitVec 32)}, ws.length = k → textBase ≤ b → b + 4 * k ≤ textBase + textLen →',
        '      CodeAt M b ws → CodeAt M\' b ws := fun hl h1 h2 hc => hc.of_eq fun x h3 h4 =>',
        '    hs\' x (by omega) (by omega)',
        '  {']
fs = []
for f in FUNCS:
    n = lean_name(f)
    fs.append(f'    {n} := hk (k := {len(funcs[f][1])}) (by decide +kernel) (by decide) (by decide) hv.{n}')
fs.append(f'    rodata := fun i b h => by')
fs.append(f'      have hl : i < {len(rbytes)} := by')
fs.append(f'        rcases Nat.lt_or_ge i rodataBytes.length with h\' | h\'')
fs.append(f'        · have : rodataBytes.length = {len(rbytes)} := by decide +kernel')
fs.append(f'          omega')
fs.append(f'        · rw [List.getElem?_eq_none h\'] at h; cases h')
fs.append(f'      rw [hs\' _ (by simp only [rodataBase, textBase]; omega) (by simp only [rodataBase, textBase, textLen]; omega)]')
fs.append(f'      exact hv.rodata i b h')
img += fs
img += ['  }', '', 'end Tom.Machine']
open(OUT_IMG, 'w').write('\n'.join(img) + '\n')
print(f'gen_code: {len(FUNCS)} functions -> {os.path.relpath(OUT, ROOT)}, {os.path.relpath(OUT_IMG, ROOT)}')
